"""Configure Alembic migrations using the migration application's database.

Offline migrations emit SQL; online migrations use the application's engine
and metadata. Custom database types receive the imports needed in revisions.
"""

from __future__ import with_statement

import logging
from logging.config import fileConfig

from alembic import context
from flask import current_app

from dioptra.restapi.db.custom_types import GUID, TZDateTime

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Interpret the config file for Python logging.
# This line sets up loggers basically.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)
logger = logging.getLogger("alembic.env")

# add your model's MetaData object here
# for 'autogenerate' support
# from myapp import mymodel
# target_metadata = mymodel.Base.metadata

config.set_main_option(
    "sqlalchemy.url",
    str(current_app.extensions["migrate"].db.engine.url).replace("%", "%%"),
)
target_metadata = current_app.extensions["migrate"].db.metadata

# other values from the config, defined by the needs of env.py,
# can be acquired:
# my_important_option = config.get_main_option("my_important_option")
# ... etc.


def get_url() -> str:
    """Return the resolved database URI from the active migration Flask context."""
    return str(current_app.config["SQLALCHEMY_DATABASE_URI"])


def render_item(type_, obj, autogen_context):
    """Render custom database types in generated revisions.

    Args:
        type_: Alembic's item category.
        obj: The item being rendered.
        autogen_context: Autogeneration context whose imports may be updated.

    Returns:
        A representation for GUID or TZDateTime types, or False to use Alembic's
        default renderer.
    """

    if type_ == "type" and isinstance(obj, GUID):
        # add import for this type
        autogen_context.imports.add("from dioptra.restapi.db.custom_types import GUID")
        return "%r" % obj

    if type_ == "type" and isinstance(obj, TZDateTime):
        # add import for this type
        autogen_context.imports.add(
            "from dioptra.restapi.db.custom_types import TZDateTime"
        )
        return "%r" % obj

    # default rendering for other objects
    return False


def run_migrations_offline() -> None:
    """Run migrations in offline mode and emit SQL to the script output.

    Configure the Alembic context with the resolved URL, metadata and literal
    bindings, then execute the migrations within an Alembic transaction.
    """
    url = get_url()
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        render_item=render_item,
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations using the migration application's existing engine.

    Open a connection for the Alembic context and close it after the migration
    transaction. The application owns the engine.
    """

    # this callback is used to prevent an auto-migration from being generated
    # when there are no changes to the schema
    # reference: http://alembic.zzzcomputing.com/en/latest/cookbook.html
    def process_revision_directives(context, revision, directives):
        """Discard an autogenerated revision when it contains no upgrade operations."""
        if getattr(config.cmd_opts, "autogenerate", False):
            script = directives[0]
            if script.upgrade_ops.is_empty():
                directives[:] = []
                logger.info("No changes in schema detected.")

    connectable = current_app.extensions["migrate"].db.engine

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            process_revision_directives=process_revision_directives,
            render_item=render_item,
            **current_app.extensions["migrate"].configure_args,
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
